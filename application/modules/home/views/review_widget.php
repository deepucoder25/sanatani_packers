<!-- Side Scroll & Arrow Script -->
<script>
document.addEventListener("DOMContentLoaded", function () {
  const track = document.getElementById("reviewsScrollTrack");
  const prevBtn = document.getElementById("revPrevBtn");
  const nextBtn = document.getElementById("revNextBtn");
  const dotsNav = document.getElementById("revDotsNav");
  const dots = dotsNav ? dotsNav.querySelectorAll(".dot-item") : [];

  if (!track) return;

  const getScrollAmount = () => {
    const card = track.querySelector(".review-card-item");
    return card ? card.offsetWidth + 24 : 300;
  };

  if (nextBtn) {
    nextBtn.addEventListener("click", () => {
      track.scrollBy({ left: getScrollAmount(), behavior: "smooth" });
    });
  }

  if (prevBtn) {
    prevBtn.addEventListener("click", () => {
      track.scrollBy({ left: -getScrollAmount(), behavior: "smooth" });
    });
  }

  // Update dots on scroll
  track.addEventListener("scroll", () => {
    const scrollPos = track.scrollLeft;
    const maxScroll = track.scrollWidth - track.clientWidth;
    const totalDots = dots.length;
    
    if (totalDots > 0 && maxScroll > 0) {
      const activeIdx = Math.min(
        totalDots - 1,
        Math.floor((scrollPos / maxScroll) * totalDots + 0.3)
      );
      dots.forEach((dot, idx) => {
        if (idx === activeIdx) {
          dot.classList.add("active");
        } else {
          dot.classList.remove("active");
        }
      });
    }
  });

  // Click dot to scroll
  dots.forEach((dot, idx) => {
    dot.addEventListener("click", () => {
      const maxScroll = track.scrollWidth - track.clientWidth;
      const targetPos = (idx / (dots.length - 1)) * maxScroll;
      track.scrollTo({ left: targetPos, behavior: "smooth" });
    });
  });
});
</script>
